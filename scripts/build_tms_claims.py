def load_records() -> dict[str, dict[str, str]]:
    with RECORDS_PATH.open(newline="", encoding="utf-8") as handle:
        return {row["pmid"]: row for row in csv.DictReader(handle)}


def source_labels(pmids: str, records: dict[str, dict[str, str]]) -> str:
    labels = []
    for pmid in [item.strip() for item in pmids.split(";") if item.strip()]:
        row = records.get(pmid)
        if row:
            labels.append(f"{pmid}: {row['title']}")
        else:
            labels.append(f"{pmid}: MISSING_FROM_CORPUS")
    return " | ".join(labels)


def write_claims(records: dict[str, dict[str, str]]) -> None:
    fields = [
        "claim_id",
        "module",
        "audience",
        "question",
        "claim",
        "patient_answer",
        "technician_detail",
        "evidence_strength",
        "source_pmids",
        "source_labels",
        "clinical_action",
        "caveat",
        "status",
    ]
    with CLAIMS_PATH.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for claim in CLAIMS:
            row = {
                "claim_id": claim["id"],
                "module": claim["module"],
                "audience": claim["audience"],
                "question": claim["question"],
                "claim": claim["claim"],
                "patient_answer": claim["patient_answer"],
                "technician_detail": claim["technician_detail"],
                "evidence_strength": claim["evidence_strength"],
                "source_pmids": claim["source_pmids"],
                "source_labels": source_labels(claim["source_pmids"], records),
                "clinical_action": claim["clinical_action"],
                "caveat": claim["caveat"],
                "status": "ready_for_training_draft_after_full_text_QA",
            }
            writer.writerow(row)


def write_patient_markdown() -> None:
    patient_claims = [
        claim
        for claim in CLAIMS
        if claim["audience"] in {"patient", "patient_and_technician"}
    ]
    grouped: dict[str, list[dict[str, str]]] = defaultdict(list)
    for claim in patient_claims:
        grouped[claim["module"]].append(claim)
    with PATIENT_MD.open("w", encoding="utf-8") as handle:
        handle.write("# Patient FAQ Claim Draft\n\n")
        handle.write("These are source-linked claim drafts for technician-delivered patient education. They should be adapted to clinic policy and clinician-approved scripts before release.\n\n")
        for module, claims in grouped.items():
            handle.write(f"## {module}\n\n")
            for claim in claims:
                handle.write(f"### {claim['question']}\n\n")
                handle.write(f"{claim['patient_answer']}\n\n")
                handle.write(f"- Evidence strength: `{claim['evidence_strength']}`\n")
                handle.write(f"- Sources: `{claim['source_pmids']}`\n")
                handle.write(f"- Boundary: {claim['caveat']}\n\n")


