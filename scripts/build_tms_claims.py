def write_coverage(records: dict[str, dict[str, str]]) -> None:
    module_counts = Counter(claim["module"] for claim in CLAIMS)
    strength_counts = Counter(claim["evidence_strength"] for claim in CLAIMS)
    source_counts: Counter[str] = Counter()
    missing: list[str] = []
    for claim in CLAIMS:
        for pmid in [item.strip() for item in claim["source_pmids"].split(";") if item.strip()]:
            source_counts[pmid] += 1
            if pmid not in records:
                missing.append(pmid)

    with COVERAGE_MD.open("w", encoding="utf-8") as handle:
        handle.write("# Claim Source Coverage\n\n")
        handle.write(f"Total extracted claims: {len(CLAIMS)}\n\n")
        handle.write("## Claims By Module\n\n")
        for module, count in module_counts.most_common():
            handle.write(f"- `{module}`: {count}\n")
        handle.write("\n## Claims By Evidence Strength\n\n")
        for strength, count in strength_counts.most_common():
            handle.write(f"- `{strength}`: {count}\n")
        handle.write("\n## Most Used Sources\n\n")
        for pmid, count in source_counts.most_common():
            title = records.get(pmid, {}).get("title", "MISSING_FROM_CORPUS")
            handle.write(f"- `{pmid}` ({count} claims): {title}\n")
        handle.write("\n## Missing PMIDs\n\n")
        if missing:
            for pmid in sorted(set(missing)):
                handle.write(f"- `{pmid}`\n")
        else:
            handle.write("None. Every claim source PMID is present in `pubmed_records.csv`.\n")


def main() -> int:
    records = load_records()
    write_claims(records)
    write_patient_markdown()
    write_technician_markdown()
    write_coverage(records)
    print(f"Wrote {CLAIMS_PATH}")
    print(f"Wrote {PATIENT_MD}")
    print(f"Wrote {TECH_MD}")
    print(f"Wrote {COVERAGE_MD}")
    return 0


